import Loading from "@/components/Loading";
import { DataForMap, DeferredAddresses } from "@/types/data";
import dynamic from "next/dynamic";
import Head from "next/head";

const Map = dynamic(() => import("@/components/Map/InnerMap"), {
  loading: () => <Loading />,
  ssr: false,
});

export interface MapPageProps {
  data: DataForMap;
  showDebugInfo?: boolean;
  ordinanceText?: string;
  year?: number;
  deferredAddresses?: DeferredAddresses;
}

export default function MapPage({
  data,
  ordinanceText,
  showDebugInfo = false,
  year,
  deferredAddresses,
}: MapPageProps) {
  return (
    <>
      <Head>
        <title>Mapa spádových oblastí pražských škol</title>
        <meta name="description" content="Generated by create next app" />
        <meta name="viewport" content="width=device-width, initial-scale=1" />
        <link rel="icon" href="/favicon.png" />
        {deferredAddresses && (
          // Start downloading addresses alongside the scripts, not after them.
          <link
            rel="preload"
            href={deferredAddresses.url}
            as="fetch"
            crossOrigin="anonymous"
          />
        )}
      </Head>
      <main>
        <Map
          data={data}
          text={ordinanceText}
          showDebugInfo={showDebugInfo}
          year={year}
          deferredAddresses={deferredAddresses}
        />
      </main>
    </>
  );
}
